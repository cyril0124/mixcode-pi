import * as path from "node:path";

const examplesDir = path.resolve(import.meta.dir, "../vendor/pi/packages/coding-agent/examples");
const output = path.resolve(import.meta.dir, "fork-examples.generated.ts");
const files: string[] = [];
for await (const file of new Bun.Glob("**/*").scan({
  cwd: examplesDir,
  onlyFiles: true,
  dot: true,
})) {
  const relativePath = file.split(path.sep).join("/");
  if (
    relativePath
      .split("/")
      .some((part) => part === "node_modules" || part === "dist" || part === ".git")
  ) {
    continue;
  }
  files.push(relativePath);
}
files.sort();
if (files.length === 0) throw new Error("Pi fork examples were not checked out");

const imports = files.map(
  (file, index) =>
    `import example${index} from ${JSON.stringify(`../vendor/pi/packages/coding-agent/examples/${file}`)} with { type: "file" };`,
);
const entries = files.map((file, index) => `  [${JSON.stringify(file)}]: example${index},`);
const content = [
  "// Generated by scripts/generate-fork-examples.ts from the pinned fork checkout.",
  ...imports,
  "",
  "export const forkExamples: Record<string, string> = {",
  ...entries,
  "};",
  "",
].join("\n");

const previous = await Bun.file(output)
  .text()
  .catch((error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return undefined;
    throw error;
  });
if (previous !== content) await Bun.write(output, content);
