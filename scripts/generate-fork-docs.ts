import * as path from "node:path";

const forkDocsDir = path.resolve(import.meta.dir, "../vendor/pi/docs");
const codingDocsDir = path.resolve(import.meta.dir, "../vendor/pi/packages/coding-agent/docs");
const output = path.resolve(import.meta.dir, "fork-docs.generated.ts");

const forkFiles: string[] = [];
for await (const file of new Bun.Glob("**/*.md").scan({ cwd: forkDocsDir, onlyFiles: true })) {
  forkFiles.push(file);
}
forkFiles.sort();
if (forkFiles.length === 0) throw new Error("Pi fork documentation was not checked out");

const codingFiles: string[] = [];
for await (const file of new Bun.Glob("**/*").scan({
  cwd: codingDocsDir,
  onlyFiles: true,
  dot: true,
})) {
  codingFiles.push(file.split(path.sep).join("/"));
}
codingFiles.sort();
if (codingFiles.length === 0) throw new Error("Pi coding-agent documentation was not checked out");

const forkImports = forkFiles.map(
  (file, index) =>
    `import doc${index} from ${JSON.stringify(`../vendor/pi/docs/${file}`)} with { type: "text" };`,
);
const codingImports = codingFiles.map(
  (file, index) =>
    `import codingDoc${index} from ${JSON.stringify(`../vendor/pi/packages/coding-agent/docs/${file}`)} with { type: "file" };`,
);
const forkEntries = forkFiles.map((file, index) => `  [${JSON.stringify(file)}]: doc${index},`);
const codingEntries = codingFiles.map(
  (file, index) => `  [${JSON.stringify(file)}]: codingDoc${index},`,
);
const content = [
  "// Generated by scripts/generate-fork-docs.ts from the pinned fork checkout.",
  ...forkImports,
  ...codingImports,
  "",
  "export const forkDocs: Record<string, string> = {",
  ...forkEntries,
  "};",
  "",
  "export const codingAgentDocs: Record<string, string> = {",
  ...codingEntries,
  "};",
  "",
].join("\n");

const previous = await Bun.file(output)
  .text()
  .catch((error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return undefined;
    throw error;
  });
if (previous !== content) await Bun.write(output, content);
